"""
UrbanFlow AI - Core Schemas
Defines all canonical Pydantic data structures used across agents,
models, simulation runners, and API endpoints.
"""

from typing import List, Dict, Any, Optional, Literal
from pydantic import BaseModel, Field


class Coordinates(BaseModel):
    lat: float
    lng: float


class RoadSegment(BaseModel):
    """
    Represents an observable, directed road corridor segment.
    """
    id: str = Field(..., description="Unique segment identifier (e.g., 'seg_01')")
    name: str = Field(..., description="Human-readable road name")
    start_node: str = Field(..., description="Origin intersection ID")
    end_node: str = Field(..., description="Destination intersection ID")
    length_km: float = Field(..., description="Length of segment in kilometers")
    speed_limit_kmh: float = Field(default=50.0, description="Speed limit in km/h")
    current_speed: float = Field(..., description="Current detected speed in km/h")
    baseline_speed: float = Field(..., description="Historical nominal free-flow speed in km/h")
    occupancy: float = Field(..., description="Current sensor occupancy ratio [0.0 - 1.0]")
    baseline_occupancy: float = Field(default=0.25, description="Historical nominal occupancy [0.0 - 1.0]")
    forecast_15m_risk: float = Field(default=0.0, description="Predicted 15-minute congestion risk [0.0 - 1.0]")
    forecast_30m_risk: float = Field(default=0.0, description="Predicted 30-minute congestion risk [0.0 - 1.0]")
    risk_level: Literal["low", "medium", "high", "critical"] = Field(
        default="low", description="Categorical risk level"
    )
    coordinates: List[List[float]] = Field(
        ..., description="Polyline coordinates as [[lat, lng], [lat, lng], ...]"
    )
    status: Literal["normal", "congested", "blocked", "priority_corridor"] = Field(
        default="normal", description="Operational road state"
    )
    incident_id: Optional[str] = Field(default=None, description="Active incident ID on this segment if any")


class CVEvidence(BaseModel):
    """
    Computer Vision observation extracted from roadside CCTV / traffic cameras.
    """
    camera_id: str
    frame_id: str
    detected_class: str = Field(..., description="Detected label: 'stopped_vehicle', 'collision', 'debris', 'clear'")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Model confidence score")
    bounding_box: Optional[List[int]] = Field(default=None, description="[ymin, xmin, ymax, xmax]")
    timestamp: str


class Incident(BaseModel):
    """
    Corroborated incident candidate with sensor and CV evidence.
    """
    id: str = Field(..., description="Incident ID (e.g., 'inc_001')")
    type: Literal["stopped_vehicle", "collision", "heavy_congestion", "debris", "roadwork"] = Field(
        ..., description="Classified incident type"
    )
    location_segment_id: str = Field(..., description="Affected road segment ID")
    location_name: str = Field(..., description="Human-readable road / intersection location")
    coordinates: List[float] = Field(..., description="[lat, lng] of the incident")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Combined belief score")
    severity: Literal["low", "medium", "high", "critical"] = Field(..., description="Operational severity")
    status: Literal["active", "cleared", "monitoring"] = Field(default="active")
    evidence: Dict[str, Any] = Field(
        default_factory=dict,
        description="Corroborating data points (sensor speed collapse, CV detection, occupancy surge)"
    )
    timestamp: str


class EmergencyRequest(BaseModel):
    """
    Active emergency dispatch requiring prioritized corridor mobility.
    """
    id: str = Field(..., description="Dispatch request ID (e.g., 'emg_001')")
    vehicle_id: str = Field(..., description="Emergency vehicle unit ID (e.g., 'AMB-104')")
    vehicle_type: Literal["ambulance", "fire_truck", "police"] = Field(default="ambulance")
    origin_node: str = Field(..., description="Starting intersection node ID")
    destination_node: str = Field(..., description="Target hospital / incident node ID")
    eta_target_seconds: float = Field(..., description="Target arrival threshold in seconds")
    current_eta_seconds: float = Field(..., description="Calculated ETA with current route")
    baseline_eta_seconds: float = Field(..., description="Baseline ETA under unoptimized congestion")
    priority: Literal["high", "critical"] = Field(default="critical")
    status: Literal["pending", "active", "completed"] = Field(default="active")
    corridor_segment_ids: List[str] = Field(default_factory=list, description="Ordered segment IDs reserved")
    priority_intersections: List[str] = Field(default_factory=list, description="Pre-empted signal intersection IDs")


class RouteOption(BaseModel):
    """
    Dynamic path option generated by RoutingAgent.
    """
    id: str = Field(..., description="'primary', 'alternative', or 'emergency_corridor'")
    name: str = Field(..., description="Descriptive route label")
    segment_ids: List[str] = Field(..., description="Ordered list of segment IDs")
    node_ids: List[str] = Field(..., description="Ordered sequence of nodes traversed")
    coordinates: List[List[float]] = Field(..., description="Polyline points [[lat, lng], ...]")
    total_distance_km: float
    estimated_time_seconds: float
    baseline_time_seconds: float
    time_savings_seconds: float = Field(default=0.0)
    total_cost: float
    is_active: bool = True
    color: str = Field(default="#3B82F6", description="Hex display color for map UI")


class Recommendation(BaseModel):
    """
    Actionable recommendation produced by the Coordinator Agent.
    """
    id: str = Field(..., description="Recommendation ID (e.g., 'rec_001')")
    action: str = Field(..., description="Concise operator command")
    affected_segments: List[str] = Field(default_factory=list)
    alternatives: List[str] = Field(default_factory=list, description="Alternative actions considered")
    expected_impact: str = Field(..., description="Quantified outcome (e.g. ETA saved, diverted traffic)")
    rationale: str = Field(..., description="Operator-facing narrative explaining what changed, why now, and trade-offs")
    confidence: float = Field(..., ge=0.0, le=1.0)
    timestamp: str
    confirmed: bool = Field(default=False, description="Whether approved by operator")


class AgentEvent(BaseModel):
    """
    Traceable log entry emitted during the multi-agent decision cycle.
    """
    event_id: str
    agent_name: Literal[
        "MonitorAgent",
        "ForecastAgent",
        "IncidentAgent",
        "RoutingAgent",
        "EmergencyAgent",
        "CoordinatorAgent",
        "ExplanationAgent"
    ]
    timestamp: str
    input_summary: str
    decision: str
    handoff_to: str
    metadata: Dict[str, Any] = Field(default_factory=dict)


class TelemetryPoint(BaseModel):
    """
    Raw simulated sensor reading per road segment.
    """
    segment_id: str
    timestamp: str
    speed: float
    occupancy: float
    sensor_anomaly: bool = False
    cv_frame_available: bool = False
    camera_id: Optional[str] = None
    cv_evidence: Optional[CVEvidence] = None

